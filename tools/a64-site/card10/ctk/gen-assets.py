#!/usr/bin/env python3
# Generates assets.h for the card10's Contiki desktop (this directory):
#   - font4x6: the X11 misc-fixed 4x6 font ("Public domain font. Share and
#     enjoy."), ASCII 32..126, one byte per row (the 4 high bits)
#   - backdrop: the desktop's 160x80 picture, RGB565: the retrocpugeek
#     avatar (retrocpugeek.png, its owner's own) on a circuit board that
#     carries on to the right, with the name in the font
#   - tiles: the desktop icons, 12x18 each, cut into 4x6 character tiles
#     (CTK draws an icon as 3x3 characters), RGB565 with TRANSPARENT where
#     the backdrop shows through
#
#   python3 tools/a64-site/card10/ctk/gen-assets.py [font.pcf.gz]
#
# Needs Pillow; the font from the X11 fonts (Ubuntu: xfonts-base,
# /usr/share/fonts/X11/misc/4x6.pcf.gz).
import gzip
import os
import sys

from PIL import Image, ImageDraw, PcfFontFile

HERE = os.path.dirname(os.path.abspath(__file__))
FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/X11/misc/4x6.pcf.gz"
W, H = 160, 80
TRANSPARENT = 0xF81F

PCB = (18, 94, 52)
PCB_DARK = (12, 62, 34)
GOLD = (214, 168, 64)
GOLD_DIM = (150, 118, 48)
PURPLE = (92, 48, 104)
CREAM = (248, 233, 190)


def rgb565(c):
    r, g, b = c[:3]
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


# The font
pcf = PcfFontFile.PcfFontFile(gzip.open(FONT))
font = []
for ch in range(32, 127):
    _, _, _, im = pcf.glyph[ch]
    rows = []
    for y in range(6):
        bits = 0
        for x in range(4):
            if im.getpixel((x, y)):
                bits |= 0x80 >> x
        rows.append(bits)
    font.append(rows)


def text(draw_im, x, y, s, colour):
    for i, ch in enumerate(s):
        rows = font[ord(ch) - 32]
        for yy in range(6):
            for xx in range(4):
                if rows[yy] & (0x80 >> xx):
                    draw_im.putpixel((x + i * 4 + xx, y + yy), colour)


# The backdrop: a circuit board, the avatar at the left
bd = Image.new("RGB", (W, H), PCB)
d = ImageDraw.Draw(bd)
# traces carrying on from the avatar's, to vias (kept dim: icons go there)
traces = [
    [(72, 20), (96, 20), (104, 12), (150, 12)],
    [(72, 34), (84, 34), (92, 42), (126, 42), (134, 50), (156, 50)],
    [(72, 58), (100, 58), (108, 66), (156, 66)],
    [(116, 12), (116, 30), (124, 30)],
    [(140, 42), (140, 30), (150, 30)],
]
for t in traces:
    d.line(t, fill=GOLD_DIM, width=1)
    for (x, y) in (t[0], t[-1]):
        d.ellipse((x - 1, y - 1, x + 1, y + 1), outline=GOLD_DIM, fill=PCB_DARK)
avatar = Image.open(os.path.join(HERE, "retrocpugeek.png")).convert("RGBA")
board = Image.new("RGBA", avatar.size, PCB + (255,))
board.alpha_composite(avatar)
bd.paste(board.convert("RGB").resize((72, 72), Image.LANCZOS), (0, 7))
text(bd, 160 - 12 * 4 - 3, 73, "RETROCPUGEEK", GOLD)

# The icons, 12x18 (transparent: magenta)
KEY = (255, 0, 255)


def icon():
    im = Image.new("RGB", (12, 18), KEY)
    return im, ImageDraw.Draw(im)


icons = {}
# the brand: the avatar's chip
im, d = icon()
chip = avatar.crop((92, 92, 308, 308))
cb = Image.new("RGBA", chip.size, PURPLE + (255,))
cb.alpha_composite(chip)
im.paste(cb.convert("RGB").resize((12, 12), Image.LANCZOS), (0, 3))
for x in (2, 5, 8):
    d.point((x + 1, 2), GOLD)
    d.point((x + 1, 15), GOLD)
icons["rcg"] = im
# the calculator
im, d = icon()
d.rectangle((1, 1, 10, 16), fill=(200, 200, 208), outline=(60, 60, 70))
d.rectangle((3, 3, 8, 6), fill=(40, 70, 50))
d.line((4, 5, 7, 5), fill=(140, 230, 140))
for row in range(3):
    for col in range(3):
        d.rectangle((3 + col * 2 + (col > 0) * 0, 8 + row * 3, 3 + col * 2, 9 + row * 3), fill=(60, 60, 70))
d.rectangle((9 - 1, 8, 9 - 1, 15), fill=GOLD)
icons["calc"] = im
# processes: a window with a list
im, d = icon()
d.rectangle((0, 2, 11, 15), fill=CREAM, outline=(40, 40, 40))
d.rectangle((0, 2, 11, 4), fill=PURPLE)
for i, y in enumerate((6, 8, 10, 12)):
    d.line((2, y, 9 - (i % 2) * 3, y), fill=(40, 40, 40))
icons["procs"] = im
# the serial terminal: a screen with a prompt
im, d = icon()
d.rectangle((0, 2, 11, 13), fill=(30, 30, 36), outline=(160, 160, 170))
d.line((2, 5, 3, 6), fill=(120, 230, 120))
d.line((3, 6, 2, 7), fill=(120, 230, 120))
d.line((5, 9, 8, 9), fill=(120, 230, 120))
d.rectangle((3, 14, 8, 15), fill=(160, 160, 170))
icons["term"] = im

out = []
out.append("/* Generated by gen-assets.py: don't edit. */")
out.append("#define ASSET_TRANSPARENT 0x%04x" % TRANSPARENT)
out.append("static const unsigned char font4x6[95][6] = {")
for rows in font:
    out.append("  {" + ",".join("0x%02x" % r for r in rows) + "},")
out.append("};")
out.append("static const unsigned short backdrop[%d][%d] = {" % (H, W))
for y in range(H):
    out.append("  {" + ",".join("0x%04x" % rgb565(bd.getpixel((x, y))) for x in range(W)) + "},")
out.append("};")
names = list(icons)
out.append("/* icon i is tiles 9*i..9*i+8 (rows of 3), characters 0x80 + tile */")
for i, n in enumerate(names):
    out.append("#define ICON_%s %d" % (n.upper(), i))
out.append("static const unsigned short tiles[%d][6][4] = {" % (9 * len(names)))
for n in names:
    im = icons[n]
    for ty in range(3):
        for tx in range(3):
            rows = []
            for y in range(6):
                px = []
                for x in range(4):
                    c = im.getpixel((tx * 4 + x, ty * 6 + y))
                    px.append(TRANSPARENT if c == KEY else rgb565(c))
                rows.append("{" + ",".join("0x%04x" % p for p in px) + "}")
            out.append("  {" + ",".join(rows) + "},")
out.append("};")
with open(os.path.join(HERE, "assets.h"), "w") as f:
    f.write("\n".join(out) + "\n")
# a preview, for looking at
prev = bd.copy()
for i, n in enumerate(names):
    ic = icons[n]
    for y in range(18):
        for x in range(12):
            c = ic.getpixel((x, y))
            if c != KEY:
                prev.putpixel((136 - i * 16 + x, 20 + y), c)
prev.resize((W * 4, H * 4), Image.NEAREST).save(os.environ.get("PREVIEW", "/dev/null"), "PNG")
